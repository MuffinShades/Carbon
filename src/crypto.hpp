void aes_cipher(byte *block, u32 *w, const size_t nk, const size_t nr) {
    if (!block)
        return;
            
    i32 i;
    
    aes_add_rkey(block, w, 0);
    
    for (i = 1; i < nr; i++) {
        aes_subbytes(block);
        aes_shftrows(block);
        aes_mixcol(block);
        aes_add_rkey(block, w, i);
    }
    
    aes_subbytes(block);
    aes_shftrows(block);
    aes_add_rkey(block, w, nr);
}

