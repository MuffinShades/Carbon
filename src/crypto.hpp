inline void aes_shftrows(byte *state) {
    i32 r,c,p;
    
    byte work_space[16] = {0};
    
    memcpy(work_space, state, 16);
    
    for (r = 0; r < 4; r++) {
        for (c = 0; c < 4; c++) {
            p = (r << 3) + ((c+r) & 3);
            
            work_space[p] = state[p];
        }
    }
    
    memcpy(state, work_space, 16);
}

inline void aes_mixcol(byte *state) {
    i32 c;
    
    byte work_space[16] = {0};
    
    memcpy(work_space, state, 16);
    
    byte s0,s1,s2,s3;
    
    for (c = 0; c < 4; c++) {
        s0 = state[c + 0]; s1 = state[c + 4];
        s2 = state[c + 8]; s3 = state[c + 12];
        
        work_space[c + 0]  = aes_mul2(s0) ^ aes_mul3(s1) ^ s2 ^ s3;
        work_space[c + 4]  = s0 ^ aes_mul2(s1) ^ aes_mul3(s2) ^ s3;
        work_space[c + 8]  = s0 ^ s1 ^ aes_mul2(s2) ^ aes_mul3(s3);
        work_space[c + 12] = aes_mul3(s0) ^ s1 ^ s2 ^ aes_mul2(s3);
    }
    
    memcpy(state, work_space, 16);
}


