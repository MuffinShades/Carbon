inline u32 subword(u32 v) {
    return 
        (sbox((v >> 24) & 0xff) << 24) |
        (sbox((v >> 16) & 0xff) << 16) |
        (sbox((v >> 8) & 0xff) << 8) |
        (sbox((v >> 0) & 0xff) << 0) ;
};

